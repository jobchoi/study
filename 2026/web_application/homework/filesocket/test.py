# =====================================================================
# 1. 불변 객체 (Immutable Object) 예시 - 정수(int), 문자열(str) 등
# =====================================================================
print("=== [1] 불변 객체(Immutable) 테스트 ===")

a = 10
b = a  # b는 a와 동일한 메모리 주소(값 10이 들어있는 방)를 가리킵니다.

print(f"처음 세팅   -> id(a) = {id(a)}, a = {a}")
print(f"처음 세팅   -> id(b) = {id(b)}, b = {b}")  # 두 id(주소) 값이 완벽히 일치!

b = 20  
# ★ 핵심: 기존 10이 있던 방을 20으로 개조한 것이 아닙니다!
# 메모리 공간에 새롭게 '20'이라는 방을 파서 b를 그리로 이사(재할당) 보낸 것입니다.

print(f"b=20 변경 후 -> id(a) = {id(a)}, a = {a}")  # a는 여전히 처음 방(10)에 남아있음
print(f"b=20 변경 후 -> id(b) = {id(b)}, b = {b}")  # b의 주소값(id)만 완전히 새로워짐

# [결론] b를 아무리 수정(재할당)해도 원본인 a에는 아무런 타격이 없습니다.


# =====================================================================
# 2. 가변 객체 (Mutable Object) 예시 - 리스트(list), 딕셔너리(dict) 등
# =====================================================================
print("\n=== [2] 가변 객체(Mutable) 테스트 ===")

list_a = [1, 2, 3]
list_b = list_a  # list_b는 list_a의 리스트 메모리 주소를 그대로 공유합니다 (포인터 개념).

print(f"처음 세팅   -> id(list_a) = {id(list_a)}, list_a = {list_a}")
print(f"처음 세팅   -> id(list_b) = {id(list_b)}, list_b = {list_b}")  # 두 id가 일치!

list_b[0] = 99  
# ★ 핵심: list_b의 '내부 알맹이'만 갈아 끼웠습니다. 
# 방 주소(id)는 바꾸지 않고 내부 요소만 수정(In-place modification)한 것입니다.

print(f"변경 작업 후 -> id(list_a) = {id(list_a)}, list_a = {list_a}")  
print(f"변경 작업 후 -> id(list_b) = {id(list_b)}, list_b = {list_b}")  
# 💥 결과: list_b만 건드렸는데 같은 주소를 공유하는 list_a까지 [99, 2, 3]으로 변해버립니다!
# 하지만 두 변수의 메모리 주소(id)는 처음과 동일하게 묶여있습니다.

# [결론] 주소를 공유한 상태에서 가변 객체의 내부를 수정하면 원본 데이터까지 실시간으로 조작됩니다.